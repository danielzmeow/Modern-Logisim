export type MessageKey = keyof (typeof messages)['zh'];

export function tr(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = (messages[lang] as Record<string, string>)[key] ?? (messages.zh as Record<string, string>)[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

export function detectLang(): Lang {
  try {
    const raw = typeof navigator !== 'undefined' ? navigator.language : 'en';
    return raw.toLowerCase().startsWith('zh') ? 'zh' : 'en';
  } catch {
    return 'en';
  }
}

export const LANG_LABEL: Record<Lang, string> = { zh: '中文', en: 'English' };

export function itemCount(lang: Lang, n: number, zhUnit: string, enOne: string, enMany = `${enOne}s`): string {
  return lang === 'zh' ? `${n} ${zhUnit}` : `${n} ${n === 1 ? enOne : enMany}`;
}
